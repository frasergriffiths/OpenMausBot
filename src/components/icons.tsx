export interface IconProps extends SVGProps<SVGSVGElement> { size?: number | string; strokeWidth?: number; absoluteStrokeWidth?: boolean; }
export type LucideIcon = ComponentType<IconProps>;
export type LucideProps = IconProps;

function kebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function make(Icon: ComponentType<SVGProps<SVGSVGElement>>, name: string) {
  const Glyph = ({ size = 24, className, color, style, strokeWidth, absoluteStrokeWidth, ...rest }: IconProps) => (
    <Icon aria-hidden className={["lucide", `lucide-${kebab(name)}`, className].filter(Boolean).join(" ")} width={size} height={size} style={{ width: size, height: size, color, ...style }} {...rest} />
  );
  return Glyph as LucideIcon;
}

